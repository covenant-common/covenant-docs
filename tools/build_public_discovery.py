#!/usr/bin/env python3
"""Generate public discovery from an observed, anonymous MCP inventory.

Default builds offline. --check compares generated bytes; --refresh explicitly
reads only initialize and tools/list from the fixed public HTTPS endpoint.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
from urllib.request import HTTPRedirectHandler, Request, build_opener

ROOT = Path(__file__).resolve().parents[1]
ORIGIN = 'https://jupie202020.pythonanywhere.com'
ENDPOINT = ORIGIN + '/mcp'
WEBSITE = 'https://covenant-common.github.io/covenant-docs'
SCHEMA = 'https://static.modelcontextprotocol.io/schemas/v1/server-card.schema.json'
SOURCE = ROOT / 'distribution' / 'public-mcp-observation.json'
NAMES = frozenset(('aap_public_listing_search', 'covenant_marketplace__quick_trade',
    'covenant_contract__draft', 'covenant_contract__inspect', 'covenant_contract__compare',
    'covenant_contract__render', 'covenant_review__review', 'covenant_review__authority',
    'covenant_review__evidence'))


def wire(value):
    return (json.dumps(value, ensure_ascii=True, sort_keys=True, indent=2) + '\n').encode('ascii')


def observe():
    class NoRedirect(HTTPRedirectHandler):
        def redirect_request(self, request, fp, code, message, headers, new_url):
            return None
    opener = build_opener(NoRedirect())
    def rpc(ident, method, params=None):
        packet = {'jsonrpc': '2.0', 'id': ident, 'method': method}
        if params is not None:
            packet['params'] = params
        request = Request(ENDPOINT, data=wire(packet), headers={
            'Content-Type': 'application/json', 'Accept': 'application/json, text/event-stream',
            'MCP-Protocol-Version': '2025-11-25'}, method='POST')
        with opener.open(request, timeout=30) as response:
            if response.geturl() != ENDPOINT or response.status != 200:
                raise ValueError('Unexpected public discovery response')
            raw = response.read(262145)
        if len(raw) > 262144:
            raise ValueError('Public metadata exceeds the bounded capture size')
        reply = json.loads(raw)
        if reply.get('id') != ident or 'error' in reply:
            raise ValueError('MCP discovery did not complete')
        return reply['result']
    initial = rpc(1, 'initialize', {'protocolVersion': '2025-11-25', 'capabilities': {},
        'clientInfo': {'name': 'covenant-public-discovery', 'version': '0.1.0'}})
    listing = rpc(2, 'tools/list')
    if listing.get('nextCursor'):
        raise ValueError('Inventory is paginated; review the complete inventory before publication')
    return {'format': 'aap-public-mcp-observation/0.1', 'endpoint': ENDPOINT,
        'observedAt': datetime.now(timezone.utc).isoformat(),
        'protocolVersion': initial['protocolVersion'], 'serverInfo': initial['serverInfo'],
        'tools': listing['tools'], 'method': 'initialize and tools/list only; no tools/call'}


def documents(source):
    if source.get('format') != 'aap-public-mcp-observation/0.1' or source.get('endpoint') != ENDPOINT:
        raise ValueError('Only the fixed public observation profile is supported')
    if source.get('protocolVersion') != '2025-11-25':
        raise ValueError('A new protocol must receive explicit review')
    tools = source['tools']
    if (type(tools) is not list or len(tools) != len(NAMES) or
            any(type(t) is not dict or t.get('name') not in NAMES for t in tools) or
            {t['name'] for t in tools} != NAMES or
            any(t.get('annotations', {}).get('readOnlyHint') is not True for t in tools)):
        raise ValueError('Public tool inventory changed; never silently omit or publish new tools')
    if any(type(t.get('description')) is not str or not t['description'].strip() or
           type(t.get('inputSchema')) is not dict or t['inputSchema'].get('type') != 'object'
           for t in tools):
        raise ValueError('Every public tool must retain its description and complete object input schema')
    inventory = {'format': 'aap-public-tool-inventory/0.1', 'endpoint': ENDPOINT,
        'observedAt': source['observedAt'], 'protocolVersion': source['protocolVersion'],
        'serverInfo': source['serverInfo'], 'toolCount': len(tools),
        'tools': sorted(tools, key=lambda t: t['name']),
        'liveAuthority': 'Discover the current tools with MCP tools/list before calling.',
        'scope': 'Anonymous public tools only; no account access, signing, publication or payment.'}
    inventory_bytes = wire(inventory)
    card_name = 'io.github.covenant-common/covenant-aap'
    card = {'$schema': SCHEMA, 'name': card_name, 'version': source['serverInfo']['version'],
        'title': 'Covenant public tools',
        'description': 'Find services, draft work terms and review supplied agreements. No signing or payment.',
        'websiteUrl': WEBSITE + '/docs/CONNECTORS.html',
        'remotes': [{'type': 'streamable-http', 'url': ENDPOINT,
            'supportedProtocolVersions': [source['protocolVersion']]}],
        '_meta': {
            'io.github.covenant-common/public-tools': {
                'url': WEBSITE + '/mcp/tool-inventory.json', 'toolCount': len(tools),
                'names': sorted(NAMES), 'observedAt': source['observedAt'],
                'sha256': hashlib.sha256(inventory_bytes).hexdigest(),
                'snapshotOnly': True, 'currentListingMethod': 'tools/list'},
            'io.github.covenant-common/runtime-identity': {
                'observedServerInfo': source['serverInfo'],
                'nameMatchesCard': source['serverInfo']['name'] == card_name,
                'note': 'Legacy runtime name retained. Verify the actual connection; this card is advisory.'},
            'io.github.covenant-common/access': {'authentication': 'none', 'privateAccountToolsIncluded': False}}}
    card_bytes = wire(card)
    catalog = {'specVersion': '1.0', 'host': {'displayName': 'Covenant',
        'documentationUrl': WEBSITE + '/docs/CONNECTORS.html'}, 'entries': [{
        'identifier': 'urn:air:jupie202020.pythonanywhere.com:mcp:covenant-aap',
        'displayName': 'Covenant public tools',
        'type': 'application/mcp-server-card+json', 'data': card}]}
    api = {'linkset': [
        # The API host does not serve this path (it 404s). Anchor the linkset
        # on the website file that actually returns these bytes.
        {'anchor': WEBSITE + '/.well-known/api-catalog.json', 'item': [{'href': ENDPOINT}]},
        {'anchor': ENDPOINT,
         'service-doc': [{'href': WEBSITE + '/docs/API_MCP.html', 'type': 'text/html'}],
         'describedby': [{'href': WEBSITE + '/.well-known/mcp/server-card.json',
                          'type': 'application/mcp-server-card+json'}]}]}
    auth = ('# Covenant public access\n\n'
        'Public MCP: ' + ENDPOINT + '\n\n'
        'The nine public search, draft and review tools need no account, token or API key. '
        'Use Streamable HTTP and MCP 2025-11-25. Discover the current schemas with tools/list. '
        'Do not send an Authorization header to this anonymous endpoint.\n\n'
        'Private account operations use a separate scoped bearer credential from account setup. '
        'Connecting this public endpoint does not create an account or grant signing or spending authority. '
        'No OAuth issuer is advertised for this service. Keep signing keys, passwords and payment credentials out of public requests.\n\n'
        'Setup and current availability: ' + WEBSITE + '/docs/API_MCP.html\n'
        'Privacy: ' + WEBSITE + '/PRIVACY.html\n')
    return {
        'mcp/server-card': ('application/mcp-server-card+json', card_bytes),
        '.well-known/mcp/server-card.json': ('application/mcp-server-card+json', card_bytes),
        '.well-known/ai-catalog.json': ('application/ai-catalog+json', wire(catalog)),
        '.well-known/api-catalog': ('application/linkset+json', wire(api)),
        # GitHub Pages types an extensionless file as application/octet-stream.
        # The same bytes with a .json name are served as application/json.
        '.well-known/api-catalog.json': ('application/json', wire(api)),
        'mcp/tool-inventory.json': ('application/json', inventory_bytes),
        'auth.md': ('text/markdown; charset=utf-8', auth.encode('utf-8'))}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group()
    action.add_argument('--check', action='store_true')
    action.add_argument('--refresh', action='store_true')
    action.add_argument('--check-live', action='store_true')
    args = parser.parse_args()
    if args.refresh:
        candidate = observe()
        documents(candidate)  # Reject drift or incomplete schemas before replacing the retained observation.
        SOURCE.write_bytes(wire(candidate))
    source = json.loads(SOURCE.read_text())
    if args.check_live:
        live = observe()
        for key in ('tools', 'serverInfo', 'protocolVersion'):
            if wire(live[key]) != wire(source[key]):
                raise SystemExit('FAIL: live public metadata drift in ' + key)
    outputs = documents(source)
    for name, (media, body) in outputs.items():
        path = ROOT / name
        if args.check or args.check_live:
            if not path.is_file() or path.read_bytes() != body:
                raise SystemExit('FAIL: stale discovery file ' + name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(body)
    manifest = {'format': 'aap-public-discovery-deployment/0.1', 'origin': ORIGIN,
        'observedAt': source['observedAt'], 'documents': [
            {'path': '/' + name, 'file': name, 'contentType': media,
             'sha256': hashlib.sha256(body).hexdigest()} for name, (media, body) in outputs.items()],
        'runtimeIdentityMatchesCard': source['serverInfo']['name'] == 'io.github.covenant-common/covenant-aap',
        'deploymentStatus': 'PREPARED_NOT_ACTIVATED',
        'githubPagesProjectPrefixIsNotDomainRoot': True}
    target = ROOT / 'distribution' / 'public-discovery-deployment.json'
    if args.check or args.check_live:
        if target.read_bytes() != wire(manifest):
            raise SystemExit('FAIL: stale deployment manifest')
    else:
        target.write_bytes(wire(manifest))
    print(json.dumps({'status': 'PASS', 'files': len(outputs), 'tools': len(NAMES),
        'live_inventory_checked': args.refresh or args.check_live,
        'runtime_identity_matches_card': manifest['runtimeIdentityMatchesCard'],
        'hosted_activation': 'NOT_ESTABLISHED_BY_THIS_COMMAND'}, indent=2))


if __name__ == '__main__':
    main()
